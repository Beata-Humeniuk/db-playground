'use strict';

const { parseSqlText } = require('../src/sqlSchema');
const { readJsonText } = require('../src/jsonSchema');
const { toEditable, diffSchemas } = require('../src/schemaEdit');
const { changesToScript, fullCreateScript } = require('../src/alterGen');

const assert = (cond, msg) => { if (!cond) { console.error('FAIL: ' + msg); process.exit(1); } };
const clone = (x) => JSON.parse(JSON.stringify(x));

const SQL = `
CREATE TABLE users (
  id integer NOT NULL PRIMARY KEY,
  email varchar(255) NOT NULL,
  nick varchar(50),
  legacy_flag char(1)
);
CREATE TABLE orders (
  id integer NOT NULL PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id)
);
`;

const { dialect, schema: baseline } = toEditable(parseSqlText(SQL));
assert(dialect === 'postgres', 'default dialect for plain SQL');

assert(diffSchemas(baseline, clone(baseline)).length === 0, 'identical schemas produce no changes');

const edited = clone(baseline);
const users = edited.tables.find((t) => t.name === 'users');
const nick = users.columns.find((c) => c.name === 'nick');
nick.name = 'nickname';
const email = users.columns.find((c) => c.name === 'email');
email.type = 'varchar(320)';
const legacy = users.columns.find((c) => c.name === 'legacy_flag');
users.columns = users.columns.filter((c) => c !== legacy);
users.columns.push({ id: 'c900', name: 'phone', type: 'varchar(30)', nullable: true, primaryKey: false, default: '', comment: 'Contact phone', autoIncrement: false });
users.indexes.push({ id: 'i901', name: 'idx_users_phone', columns: ['phone'], unique: false });
const orders = edited.tables.find((t) => t.name === 'orders');
orders.name = 'customer_orders';
edited.tables.push({
  id: 't902', name: 'payments', comment: 'Payments',
  columns: [
    { id: 'c903', name: 'id', type: 'bigint', nullable: false, primaryKey: true, default: '', comment: '', autoIncrement: true },
    { id: 'c904', name: 'order_id', type: 'integer', nullable: false, primaryKey: false, default: '', comment: '', autoIncrement: false },
  ],
  indexes: [],
});
edited.relations.push({ id: 'r905', name: 'fk_payments_order', fromTable: 'payments', fromColumns: ['order_id'], toTable: 'customer_orders', toColumns: ['id'] });

const changes = diffSchemas(baseline, edited);
const kinds = changes.map((c) => c.kind);
for (const expected of ['renameColumn', 'modifyColumn', 'dropColumn', 'addColumn', 'addIndex', 'renameTable', 'createTable', 'addRelation']) {
  assert(kinds.includes(expected), 'diff contains ' + expected + ', got: ' + kinds.join(', '));
}
assert(!kinds.includes('setPrimaryKey'), 'rename does not touch the primary key');

const pgScript = changesToScript(changes, 'postgres');
assert(pgScript.includes('ALTER TABLE orders RENAME TO customer_orders;'), 'pg rename table, got:\n' + pgScript);
assert(pgScript.includes('ALTER TABLE users RENAME COLUMN nick TO nickname;'), 'pg rename column');
assert(pgScript.includes('ALTER TABLE users ALTER COLUMN email TYPE varchar(320);'), 'pg change type');
assert(pgScript.includes('ALTER TABLE users ADD COLUMN phone varchar(30);'), 'pg add column');
assert(pgScript.includes("COMMENT ON COLUMN users.phone IS 'Contact phone';"), 'pg column comment');
assert(pgScript.includes('ALTER TABLE users DROP COLUMN legacy_flag;'), 'pg drop column');
assert(pgScript.includes('CREATE TABLE payments ('), 'pg create table');
assert(pgScript.includes('GENERATED BY DEFAULT AS IDENTITY'), 'pg identity for autoIncrement');
assert(pgScript.includes('CREATE INDEX idx_users_phone ON users (phone);'), 'pg create index');
assert(pgScript.includes('ALTER TABLE payments ADD CONSTRAINT fk_payments_order FOREIGN KEY (order_id) REFERENCES customer_orders (id);'), 'pg add fk');
assert(pgScript.indexOf('RENAME TO') < pgScript.indexOf('ADD CONSTRAINT fk_payments_order'), 'renames come before FK additions');

const myScript = changesToScript(changes, 'mysql');
assert(myScript.includes('RENAME TABLE orders TO customer_orders;'), 'mysql rename table');
assert(myScript.includes('ALTER TABLE users MODIFY COLUMN email varchar(320) NOT NULL;'), 'mysql modify column, got:\n' + myScript);
assert(myScript.includes('AUTO_INCREMENT'), 'mysql auto_increment in create');

const oraScript = changesToScript(changes, 'oracle');
assert(oraScript.includes('ALTER TABLE users ADD (phone varchar(30));'), 'oracle add column');
assert(oraScript.includes('ALTER TABLE users MODIFY (email varchar(320));'), 'oracle modify type');

const msScript = changesToScript(changes, 'mssql');
assert(msScript.includes("EXEC sp_rename 'orders', 'customer_orders';"), 'mssql rename table');
assert(msScript.includes("EXEC sp_rename 'users.nick', 'nickname', 'COLUMN';"), 'mssql rename column');

const mongoBase = toEditable(readJsonText('{"_id":{"$oid":"6613f0a2e4b0a1a2b3c4d5e6"},"name":"Ala","old":1}', { name: 'customers' }));
assert(mongoBase.dialect === 'mongo', 'json source defaults to mongo dialect');
const mongoEdited = clone(mongoBase.schema);
const coll = mongoEdited.tables[0];
coll.columns.find((c) => c.name === 'name').name = 'fullName';
coll.columns = coll.columns.filter((c) => c.name !== 'old');
coll.columns.push({ id: 'c950', name: 'segment', type: 'string', nullable: true, primaryKey: false, default: '"standard"', comment: '', autoIncrement: false });
coll.indexes.push({ id: 'i951', name: 'idx_segment', columns: ['segment'], unique: false });

const mongoScript = changesToScript(diffSchemas(mongoBase.schema, mongoEdited), 'mongo');
assert(mongoScript.includes('$rename'), 'mongo rename, got:\n' + mongoScript);
assert(mongoScript.includes('"name": "fullName"'), 'mongo rename mapping');
assert(mongoScript.includes('$unset'), 'mongo drop field');
assert(mongoScript.includes('$set') && mongoScript.includes('"standard"'), 'mongo add field with default');
assert(mongoScript.includes('createIndex'), 'mongo create index');

const full = fullCreateScript(edited, 'postgres');
assert(full.includes('CREATE TABLE users ('), 'full script has users');
assert(full.includes('CREATE TABLE payments ('), 'full script has payments');
assert(full.includes('PRIMARY KEY (id)'), 'full script has PK');

console.log('diff-alter-test OK');
